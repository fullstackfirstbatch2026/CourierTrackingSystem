const generateChartData = (days) => {
  const data = [];
  const now = new Date("2026-10-03");
  for (let i = days - 1; i >= 0; i--) {
    const d = new Date(now);
    d.setDate(d.getDate() - i);
    const label = d.toLocaleDateString("en-IN", { month: "short", day: "numeric" });
    const delivered = Math.floor(Math.random() * 30 + 20);
    const inTransit = Math.floor(Math.random() * 15 + 5);
    const exceptions = Math.floor(Math.random() * 4);
    data.push({
      date: label,
      delivered,
      inTransit,
      exceptions,
      total: delivered + inTransit + exceptions,
    });
  }
  return data;
};

